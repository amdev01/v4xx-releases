        REQUESTED_SOURCE_DIR=""
        ;;
      9)
        if [[ "$BUILD_TYPE" != "lineage" ]]; then
          warn "Bootimage builds are lineage-only"
          continue
        fi
        echo "  1) v400  2) v410  3) v480  4) v490"
        read -r -p "Select device: " dev_choice
        case "$dev_choice" in
          1|2|3|4)
            DEVICE="${DEVICES[$((dev_choice - 1))]}"
            BUILD_BOOTIMAGE=1
            PATCH_MAGISK=0
            read -r -p "Patch boot.img with Magisk? [y/N]: " magisk_choice
            case "$magisk_choice" in
              y|Y|yes|Yes|YES)
                PATCH_MAGISK=1
                if [[ -z "$MAGISK_APK" ]]; then
                  read -r -p "Path to Magisk.apk: " MAGISK_APK
                fi
                validate_magisk_opts
                ;;
            esac
            build_selected_devices
            BUILD_BOOTIMAGE=0
            PATCH_MAGISK=0
            DEVICE=""
            ;;
          *) warn "Invalid selection" ;;
        esac
        ;;
      10)
        if [[ "$BUILD_TYPE" != "lineage" ]]; then
          warn "Magisk patching is lineage-only"
          continue
        fi
        echo "  1) v400  2) v410  3) v480  4) v490"
        read -r -p "Select device: " dev_choice
        case "$dev_choice" in
          1|2|3|4)
            DEVICE="${DEVICES[$((dev_choice - 1))]}"
            PATCH_MAGISK=1
            BUILD_BOOTIMAGE=0
            if [[ -z "$MAGISK_APK" ]]; then
              read -r -p "Path to Magisk.apk: " MAGISK_APK
            fi
            validate_magisk_opts
            patch_selected_devices_magisk
            PATCH_MAGISK=0
            DEVICE=""
            ;;
          *) warn "Invalid selection" ;;
        esac
        ;;
      b|B) return ;;
      *) warn "Invalid selection" ;;
    esac
  done
}

interactive_menu() {
  while true; do
    echo
    echo "LG G Pad 7 v4xx build menu"
    echo "  TWRP source:    ${TWRP_SOURCE_DIR:-<not configured>}"
    echo "  Lineage source: ${LINEAGE_SOURCE_DIR:-<not configured>}"
    echo "  Release:        ${RELEASE_DIR}"
    echo
    echo "  1) TWRP"
    echo "  2) LineageOS 14.1"
    echo "  3) Install shared host dependencies"
    echo "  q) Quit"
    read -r -p "Select: " choice
    case "$choice" in
      1) type_menu twrp ;;
      2) type_menu lineage ;;
      3) setup_host ;;
      q|Q) exit 0 ;;
      *) warn "Invalid selection" ;;
    esac
  done
}

main() {
  load_conf
  parse_args "$@"

  if [[ -n "$BUILD_TYPE" ]]; then
    select_type "$BUILD_TYPE"
  elif [[ -n "$REQUESTED_SOURCE_DIR" || "$DO_SYNC" -eq 1 ||
          ${#SYNC_PROJECTS[@]} -gt 0 || -n "$DEVICE" ]]; then
    die "--type twrp|lineage is required for source, sync, and build operations"
  fi

  if [[ "$DO_SETUP" -eq 1 ]]; then
    setup_host
    if [[ -n "$REQUESTED_SOURCE_DIR" ]]; then
      setup_source_tree
    fi
  elif [[ -n "$REQUESTED_SOURCE_DIR" ]]; then
    install_repo_tool
    setup_source_tree
  fi

  if [[ "$DO_SYNC" -eq 1 ]]; then
    sync_sources
  fi
  if [[ -n "$DEVICE" ]]; then
    validate_magisk_opts
    save_conf
    # --magisk without --bootimage patches an existing release boot.img only.
    if [[ "$PATCH_MAGISK" -eq 1 && "$BUILD_BOOTIMAGE" -eq 0 ]]; then
      patch_selected_devices_magisk
    else
      build_selected_devices
    fi
  fi

  if [[ "$DO_SETUP" -eq 0 && "$DO_SYNC" -eq 0 && -z "$DEVICE" &&
        -z "$REQUESTED_SOURCE_DIR" ]]; then
    interactive_menu
  fi
}

main "$@"
